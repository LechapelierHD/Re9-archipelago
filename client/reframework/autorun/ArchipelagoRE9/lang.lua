    -- textes calculés, traduits par motif
    local PATTERNS = {
        { "^clé %+ position %((.-)%)$", "key + position (%s)" },
        { "^objet %+ position %((.-)%)$", "item + position (%s)" },
    }

    function ctx.T(s)
        if ctx.LANG ~= "en" or s == nil then return s end
        local t = EN[s]
        if t then return t end
        if type(s) == "string" then
            for _, p in ipairs(PATTERNS) do
                local v = s:match(p[1])
                if v then return string.format(p[2], v) end
            end
        end
        return s
    end

    function ctx.TF(fmt, ...)
        return string.format(ctx.T(fmt), ...)
    end

    function ctx.set_language(code)
        for _, l in ipairs(ctx.LANGUAGES) do
            if l[1] == code then
                ctx.LANG = code
                pcall(json.dump_file, FILE, { lang = code }, 4)
                return
            end
        end
    end

    do
        local ok, saved = pcall(json.load_file, FILE)
        if ok and type(saved) == "table" and saved.lang == "en" then ctx.LANG = "en" end
    end
